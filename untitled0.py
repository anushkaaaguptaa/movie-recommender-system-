#we need top 3 characters from cast

import ast  # for safely evaluating the string

def convert3(text):
    L = []
    counter = 0
    # convert string to list of dicts
    for i in ast.literal_eval(text):
        if counter < 3:
            L.append(i['name'])
            counter += 1
        else:
            break
    return L

# Apply the function
movies['cast'] = movies['cast'].apply(convert3)

# Check the result
movies.head()

import ast

def fetch_director(text):
    L = []
    for i in ast.literal_eval(text):
        if i['job'] == 'Director':
            L.append(i['name'])
    return L

movies['crew'] = movies['crew'].apply(fetch_director)

movies.head()

#convert "overview" string into a list
movies['overview']= movies['overview'].apply(lambda x: x.split())

#before concatenating all columns into 1 single column of tags, we need to remove spaces: Sam Worthington -> SamWorthington
#Sam Mendes -> SamMendes

movies['genres']= movies['genres'].apply(lambda x: [i.replace(" ", "") for i in x])  #science fiction -> sciencefiction

movies['keywords']= movies['keywords'].apply(lambda x: [i.replace(" ", "") for i in x])
movies['cast']= movies['cast'].apply(lambda x: [i.replace(" ", "") for i in x])
movies['crew']= movies['crew'].apply(lambda x: [i.replace(" ", "") for i in x])

movies.head()

#NOW FINALLY WE CAN CONCATINATE THESE COLUMNS INTO 1 NEW COLUMN CALLED "TAGS"
movies['tags']= movies['overview'] + movies['genres'] + movies ['keywords'] + movies['cast'] + movies['crew']

