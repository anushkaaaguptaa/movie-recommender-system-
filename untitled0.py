import nltk

from nltk.stem.porter import PorterStemmer
ps= PorterStemmer()

def stem(text):
  y= []
  for i in text.split():
    y.append(ps.stem(i))

  return " ". join(y)

new_df['tags']= new_df['tags'].apply(stem)

from sklearn.feature_extraction.text import CountVectorizer
#make a class
cv= CountVectorizer(max_features= 5000, stop_words='english')
vectors= cv.fit_transform(new_df['tags']).toarray() #convert into array to reduce sparse 0 values
cv.get_feature_names_out()

#VECTORS OF EACH MOVIE HAVE BEEN MADE
#NOW WE WISH TO CALCULATE DISTANCE OF EACH MOVIE FROM THE OTHER MOVIE
# DIST MORE SIMILARITY LESS

#WE DONT CALCULATE EUCLIDIAN DISTANCE -> INSTEAD WE WILL CALCULATE THE COSINE DISTANCE (ANGLES)
# EUCLIDIAN DISTANCE FAILS WHEN WE'VE HIGH DIMENSIONAL DATA

#cosine similarity function in skicit learn
from sklearn.metrics.pairwise import cosine_similarity

similarity= cosine_similarity(vectors)

similarity[0]  #1st movie ka baaki movies ke sath similarity score => 1st ka 1st ke sath score 1 hoga

sorted(list(enumerate(similarity[0])), reverse= True, key= lambda x: x[1]) [1:6]

def recommend(movie):
  #fetch index
  movie_index= new_df[new_df['title']== movie]. index[0]
  distances= similarity[movie_index]
  #sort similarity distances
  #zada similarity score means zada similar
  movies_list=   sorted(list(enumerate(distances)), reverse= True, key= lambda x: x[1]) [1:6]

  for i in movies_list:
    print(new_df.iloc[i[0]].title)

recommend('Avatar')